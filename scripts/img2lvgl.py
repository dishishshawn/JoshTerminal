# Convert an image to an LVGL 8 C array (RGB565 + 8-bit alpha, LV_COLOR_16_SWAP 0).
# usage: uv run --with pillow python scripts/img2lvgl.py <input> <name> <size> [knockout] > src/<name>.c
#   size: "40" (square) or "40x46"
#   knockout: white shape with the image's white parts cut out, so the background colour shows
#   through (turns the orange Reddit logo into a white badge with the Snoo punched out)
import sys

from PIL import Image

src, name, size = sys.argv[1], sys.argv[2], sys.argv[3]
w, h = (int(v) for v in size.split("x")) if "x" in size else (int(size), int(size))
im = Image.open(src).convert("RGBA")
if "knockout" in sys.argv[4:]:
    out = Image.new("RGBA", im.size)
    for y in range(im.size[1]):
        for x in range(im.size[0]):
            r, g, b, a = im.getpixel((x, y))  # type: ignore[misc]
            white = max(0, min(255, (min(g, b) - 40) * 255 // 200))
            out.putpixel((x, y), (255, 255, 255, (255 - white) * a // 255))
    im = out
im = im.resize((w, h), Image.Resampling.LANCZOS)
px = im.load()
assert px is not None

data = bytearray()
for y in range(h):
    for x in range(w):
        r, g, b, a = px[x, y]  # type: ignore[misc]
        c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += bytes((c & 0xFF, c >> 8, a))  # little-endian RGB565, then alpha
assert len(data) == w * h * 3

rows = ",\n".join(
    "  " + ", ".join(f"0x{v:02x}" for v in data[i : i + 24])
    for i in range(0, len(data), 24)
)
print(f"""// Generated by scripts/img2lvgl.py from {src}; do not edit.
#include <lvgl.h>

static const uint8_t {name}_map[] = {{
{rows}
}};

const lv_img_dsc_t {name} = {{
    .header = {{.cf = LV_IMG_CF_TRUE_COLOR_ALPHA, .always_zero = 0, .reserved = 0, .w = {w}, .h = {h}}},
    .data_size = {len(data)},
    .data = {name}_map,
}};""")
