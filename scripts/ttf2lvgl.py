# Convert a TTF/OTF to an LVGL 8 bitmap font (4 bpp, sparse cmap, no kerning).
# usage: uv run --with pillow python scripts/ttf2lvgl.py <font file> <name> <px> <chars> > src/fonts/<name>.c
#   <chars> "ascii" = printable ASCII ("ascii\u2212" adds U+2212); otherwise exactly those characters
import sys

from PIL import Image, ImageDraw, ImageFont

path, name, px, chars = sys.argv[1], sys.argv[2], int(sys.argv[3]), sys.argv[4]
if chars.startswith("ascii"):  # "ascii" plus any extra characters after it
    chars = "".join(chr(c) for c in range(0x20, 0x7F)) + chars[5:]
cps = sorted({ord(c) for c in chars})
font = ImageFont.truetype(path, px)
ascent, descent = font.getmetrics()

bits = []  # 4-bit values, packed continuously across rows (LVGL bitmap_format 0)
dscs = [
    "    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id 0 reserved */"
]
for cp in cps:
    ch = chr(cp)
    adv = round(font.getlength(ch) * 16)
    x0, y0, x1, y1 = (int(v) for v in font.getbbox(ch, anchor="ls"))  # relative to the baseline
    w, h = max(0, x1 - x0), max(0, y1 - y0)
    start = len(bits) // 2
    if w and h:
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        px_ = img.load()
        assert px_ is not None
        bits += [px_[x, y] >> 4 for y in range(h) for x in range(w)]
        if len(bits) % 2:
            bits.append(0)  # each glyph starts on a byte boundary
    else:
        w = h = x0 = y1 = 0
    assert adv < 4096 and w < 256 and h < 256
    dscs.append(
        f"    {{.bitmap_index = {start}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, "
        f".ofs_x = {x0}, .ofs_y = {-y1}}} /* {ch!r} */"
    )

data = bytes((bits[i] << 4) | bits[i + 1] for i in range(0, len(bits), 2))
rows = ",\n".join(
    "    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 20])
    for i in range(0, len(data), 20)
)
ulist = ", ".join(str(cp - cps[0]) for cp in cps)

print(f"""// Generated by scripts/ttf2lvgl.py: {path.split("/")[-1]} {px}px, {len(cps)} glyphs. Do not edit.
#include <lvgl.h>

static const uint8_t glyph_bitmap[] = {{
{rows}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{("," + chr(10)).join(dscs)}
}};

static const uint16_t unicode_list[] = {{{ulist}}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = {cps[0]}, .range_length = {cps[-1] - cps[0] + 1}, .glyph_id_start = 1,
     .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(cps)},
     .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}
}};

static lv_font_fmt_txt_glyph_cache_t cache;
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4, .kern_classes = 0,
    .bitmap_format = 0, .cache = &cache}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -1,
    .underline_thickness = 1,
    .dsc = &font_dsc}};""")
